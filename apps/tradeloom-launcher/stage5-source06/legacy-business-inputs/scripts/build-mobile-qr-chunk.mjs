import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const shellRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const vendorPath = join(shellRoot, 'vendor', 'qrcode-generator-2.0.4.js')
const outputPath = join(shellRoot, 'client.mobile-qr.js')
const vendor = await readFile(vendorPath, 'utf8')

if (!vendor.includes('Copyright (c) 2009 Kazuhiko Arase') || !vendor.includes('return qrcode;')) {
  throw new Error('Pinned qrcode-generator source is missing its attribution or expected factory contract.')
}

const chunk = `// Generated by scripts/build-mobile-qr-chunk.mjs from vendor/qrcode-generator-2.0.4.js (MIT).
window.__ModuleLoader__.load({
  id: '@tradeloom/dsh-business-shell',
  chunk: 'client.mobile-qr.js',
  factory(_require) {
    var exports;
    var module;
    var define;
${vendor}
    qrcode.stringToBytes = qrcode.stringToBytesFuncs['UTF-8'];
    return {
      createQrMatrix(value) {
        if (typeof value !== 'string' || value.length === 0 || value.length > 4096) {
          throw new TypeError('A bounded non-empty URL is required for QR encoding.');
        }
        const code = qrcode(0, 'M');
        code.addData(value, 'Byte');
        code.make();
        const size = code.getModuleCount();
        const modules = Array.from({ length: size }, (_, row) => {
          let line = '';
          for (let col = 0; col < size; col++) line += code.isDark(row, col) ? '1' : '0';
          return line;
        });
        return { size, quietZone: 4, modules };
      },
    };
  },
});
`

await writeFile(outputPath, chunk, 'utf8')
process.stdout.write('Built client.mobile-qr.js from the pinned MIT encoder source.\n')
