// Run against a real browser DOM with the actual AgentDirectory component.
// The isolated Electron15 runner supplies synthetic GET-only DTOs and React18.
const assert = require('node:assert/strict')
if (!process.versions.electron) require('node:test')('capability real ReactDOM browser contract', { skip: 'Run the isolated capability-main.cjs Electron15 harness; plain Node has no browser DOM.' }, () => {})
exports.run = async function run({window, publish, calls, capture}) {
  const document = window.document
  const wait = async fn => { for (let i=0;i<100;i++) { if(fn()) return; await new Promise(r=>setTimeout(r,10)) } throw new Error('DOM condition timed out') }
  const button = label => [...document.querySelectorAll('button')].find(n=>n.textContent===label || n.getAttribute('aria-label')===label)
  const panel = ()=>document.querySelector('.tl-agent-capabilities')
  const group = id=>document.getElementById(id)?.closest('details')
  const reload = async data => { publish(data); button('重新读取').click(); await new Promise(r=>setTimeout(r,30)); await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title')) }
  button('查看 MCP 与 Skill 能力').click()
  await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title'))
  const mcp=group('tl-capability-mcp-title'), tools=group('tl-capability-tools-title')
  assert(mcp.open); assert(!tools.open)
  assert.match(mcp.querySelector('summary').textContent,/已返回 2 项/)
  assert.match(mcp.textContent,/服务归属与连接状态：未知/)
  assert.equal(mcp.querySelectorAll('li').length,2)
  assert.equal(mcp.querySelector('code').textContent,'mcp__server_with_underscores__long_tool_name_完整名称')
  assert.equal(mcp.querySelector('input'),null,'read-only MCP tools must not gain a switch')
  assert.match(tools.textContent,/含上方 MCP 工具/)
  tools.querySelector('summary').click(); assert(tools.open)
  mcp.querySelector('summary').click(); assert(!mcp.open)
  mcp.querySelector('summary').click(); assert(mcp.open)
  mcp.querySelector('summary').focus(); assert.equal(document.activeElement,mcp.querySelector('summary'))
  await window.fixtureKey('Space'); assert(!mcp.open,'Space collapses the native summary')
  mcp.querySelector('summary').focus()
  await window.fixtureKey('Space'); assert(mcp.open,'Space expands the native summary')
  const skill=panel().querySelector('.tl-capability-skill-card'); skill.click()
  await wait(()=>skill.getAttribute('aria-pressed')==='true')
  assert.equal(skill.getAttribute('aria-expanded'),'true')
  await capture('populated')
  mcp.querySelector('summary').click();await new Promise(r=>setTimeout(r,30))
  const long = 'mcp__不可按名字拆分服务器__'+'很长的工具名称_'.repeat(18)
  await reload({mcp:{status:'visible_tool',visibleTools:Array.from({length:200},(_,i)=>i?`mcp__fixture__tool_${i}`:long),visibleToolsTruncated:true}})
  assert(!group('tl-capability-mcp-title').open,'refresh preserves collapsed MCP group')
  assert(group('tl-capability-tools-title').open,'refresh preserves expanded tool directory')
  group('tl-capability-mcp-title').querySelector('summary').click()
  assert.match(group('tl-capability-mcp-title').querySelector('summary').textContent,/已返回 200 项/)
  assert.match(group('tl-capability-mcp-title').textContent,/列表已截断.*完整数量未知/s)
  assert.equal(group('tl-capability-mcp-title').querySelector('code').textContent,long)
  assert.match(panel().querySelector('.tl-agent-capabilities-counts').textContent,/已截断/)
  await capture('truncated')
  const last=group('tl-capability-mcp-title').querySelector('li:last-child');last.scrollIntoView({block:'nearest'})
  await capture('last-tool')
  assert.match(last.textContent,/tool_199/)
  await reload({mcp:{status:'declared_only',visibleTools:null,visibleToolsTruncated:false}})
  assert.match(group('tl-capability-mcp-title').querySelector('summary').textContent,/数量未知/)
  assert.doesNotMatch(group('tl-capability-mcp-title').textContent,/已返回 0/)
  assert.match(group('tl-capability-mcp-title').textContent,/不代表当前会话已连接/)
  await capture('unknown')
  await reload({mcp:{status:'not_configured',visibleTools:[],visibleToolsTruncated:false},tools:{status:'available',items:[],total:0,truncated:false}})
  assert.match(group('tl-capability-mcp-title').querySelector('summary').textContent,/已返回 0 项/)
  assert.match(group('tl-capability-tools-title').querySelector('summary').textContent,/0 项/)
  assert.match(group('tl-capability-tools-title').textContent,/没有已列出的工具/)
  await capture('zero')
  publish({failure:true});button('重新读取').click(); await wait(()=>!!panel()?.querySelector('[role="alert"]'))
  assert.equal(panel().querySelector('details.tl-capability-disclosure'),null)
  assert.match(panel().querySelector('[role="alert"]').textContent,/能力信息暂时无法读取/)
  button('重试').focus();assert.equal(document.activeElement,button('重试'))
  await capture('error')
  publish({});button('重试').click();await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title'))
  button('已保存配置').click();await wait(()=>!!panel()?.querySelector('.tl-config-server'))
  assert.match(panel().textContent,/当前运行中的会话继续使用其原有能力/)
  const config=panel().querySelector('.tl-config-server'); config.open=true
  assert.match(config.textContent,/连接失败时停止启动/)
  assert.equal(config.querySelector('input').value,'saved-server_原标识')
  assert(button('保存默认配置'));assert(button('添加 MCP 服务'));assert(button('用已保存配置新建对话'))
  button('当前能力').click();await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title'))
  const select=panel().querySelector('select');select.value='product';select.dispatchEvent(new window.Event('change',{bubbles:true}))
  await wait(()=>panel().querySelector('h3').textContent.includes('商品助手'))
  await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title'))
  window.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));await wait(()=>!panel())
  assert.equal(document.activeElement.getAttribute('aria-label'),'选择助手')
  button('查看 MCP 与 Skill 能力').click();await wait(()=>!!panel()?.querySelector('#tl-capability-mcp-title'))
  button('关闭助手能力与配置').click();await wait(()=>!panel())
  assert(calls.length>0 && calls.every(c=>c.method==='GET'),'no mutation requests')
  return {assertions:'passed',requests:calls.length}
}
